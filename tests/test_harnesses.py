def test_external_harness_resolves_a_clean_snapshot_from_named_revision(tmp_path: Path) -> None:
    bare = tmp_path / "acme/efficient-harness.git"
    bare.parent.mkdir()
    _run("git", "init", "--bare", "--initial-branch=main", str(bare), cwd=tmp_path)
    checkout = tmp_path / "efficient-harness"
    _git_repository(checkout, remote=str(bare))
    entrypoint = checkout / "harness/00-INDEX.md"
    entrypoint.parent.mkdir(parents=True)
    entrypoint.write_text("committed rules\n", encoding="utf-8")
    _run("git", "add", ".", cwd=checkout)
    _run("git", "commit", "-m", "rules", cwd=checkout)
    _run("git", "push", "-u", "origin", "main", cwd=checkout)
    revision = _run("git", "rev-parse", "HEAD", cwd=checkout)
    entrypoint.write_text("new local rules must not leak\n", encoding="utf-8")
    _run("git", "add", ".", cwd=checkout)
    _run("git", "commit", "-m", "local rules", cwd=checkout)
    local_head = _run("git", "rev-parse", "HEAD", cwd=checkout)
    config = _config(
        tmp_path,
        HarnessConfig(
            mode="external",
            source="acme/efficient-harness",
            ref="origin/main",
            entrypoint="harness/00-INDEX.md",
        ),
    )
    (config.repo_path / "AGENTS.md").write_text(
        "Shared Harness: canonical repo `acme/efficient-harness`.\n", encoding="utf-8"
    )

    context = resolve_harness(
        config,
        registry={"acme/efficient-harness": checkout},
        snapshot_root=tmp_path / "snapshots",
    )

    assert context.mode == "external"
    assert context.source == "acme/efficient-harness"
    assert context.revision == revision
    assert context.entrypoint.read_text(encoding="utf-8") == "committed rules\n"
    assert context.context_root.is_relative_to(tmp_path / "snapshots")
    assert not context.context_root.is_relative_to(config.repo_path)
    assert _run("git", "rev-parse", "HEAD", cwd=checkout) == local_head
    assert _run("git", "status", "--porcelain", cwd=checkout) == ""


def test_external_harness_remote_mismatch_is_typed(tmp_path: Path) -> None:
    checkout = tmp_path / "wrong-harness"
    _git_repository(checkout, remote="https://github.com/acme/wrong-harness.git")
    config = _config(
        tmp_path,
        HarnessConfig(
            mode="external",
            source="acme/efficient-harness",
            ref="origin/main",
            entrypoint="harness/00-INDEX.md",
        ),
    )
    (config.repo_path / "AGENTS.md").write_text(
        "Shared Harness: canonical repo `acme/efficient-harness`.\n", encoding="utf-8"
    )

    with pytest.raises(HarnessResolutionError) as error:
        resolve_harness(config, registry={"acme/efficient-harness": checkout})

    assert error.value.reason_code == "harness-identity-mismatch"


