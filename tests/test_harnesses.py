from __future__ import annotations

import subprocess
from pathlib import Path

import pytest

from touchstone.config import Config, ConfigError, HarnessConfig, load
from touchstone.harnesses import HarnessResolutionError, load_registry, resolve_harness


def _run(*argv: str, cwd: Path) -> str:
    completed = subprocess.run(argv, cwd=cwd, check=True, capture_output=True, text=True)
    return completed.stdout.strip()


def _config(tmp_path: Path, harness: HarnessConfig) -> Config:
    root = tmp_path / "target"
    (root / ".touchstone").mkdir(parents=True)
    (root / ".touchstone/generated.toml").write_text(
        """\
[metadata]
package_version = "0.1.2"
source_digest = "sha256:test"
[metadata.profile_versions]
""",
        encoding="utf-8",
    )
    external = (
        f'source = "{harness.source}"\nref = "{harness.ref}"\n'
        if harness.mode == "external"
        else ""
    )
    (root / "touchstone.toml").write_text(
        f'''\
version = 2
generated = ".touchstone/generated.toml"
[project]
path = "."
[forge]
slug = "acme/target"
[engine]
name = "codex"
model = "gpt-test"
[harness]
mode = "{harness.mode}"
entrypoint = "{harness.entrypoint}"
{external}
[loop.code]
brief = "builtin:code-audit"
label = "touchstone:audit"
''',
        encoding="utf-8",
    )
    return load(root / "touchstone.toml")


def _git_repository(path: Path, *, remote: str | None = None) -> str:
    path.mkdir(parents=True)
    _run("git", "init", "-b", "main", cwd=path)
    _run("git", "config", "user.name", "Test", cwd=path)
    _run("git", "config", "user.email", "test@example.invalid", cwd=path)
    if remote:
        _run("git", "remote", "add", "origin", remote, cwd=path)
    return path.as_posix()


def test_embedded_harness_resolves_generated_provenance(tmp_path: Path) -> None:
    config = _config(tmp_path, HarnessConfig(mode="embedded", entrypoint="AGENTS.md"))
    (config.repo_path / "AGENTS.md").write_text(
        "<!-- Generated by Misoto Harness; version=0.1.0 source=abc123 content=def456 -->\n",
        encoding="utf-8",
    )

    context = resolve_harness(config)

    assert context.mode == "embedded"
    assert context.source == "repository"
    assert context.entrypoint == (config.repo_path / "AGENTS.md").resolve()
    assert context.revision == "abc123"
    assert context.context_root == config.repo_path
    assert context.evidence == ("generated-source:abc123",)


def test_embedded_harness_can_resolve_from_fetched_run_worktree(tmp_path: Path) -> None:
    config = _config(tmp_path, HarnessConfig(mode="embedded", entrypoint="AGENTS.md"))
    (config.repo_path / "AGENTS.md").write_text("stale checkout rules\n", encoding="utf-8")
    worktree = tmp_path / "run-worktree"
    worktree.mkdir()
    (worktree / "AGENTS.md").write_text(
        "<!-- Generated by Misoto Harness; source=fetched123 -->\n", encoding="utf-8"
    )

    context = resolve_harness(config, target_checkout=worktree)

    assert context.context_root == worktree.resolve()
    assert context.revision == "fetched123"


